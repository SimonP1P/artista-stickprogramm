/** Zufälliger Spruch, nach Möglichkeit ein anderer als `bisher`. */
export function zufallsSpruch(bisher?: string): string {
  if (SPRUECHE.length < 2) return SPRUECHE[0] ?? "";
  let s = bisher;
  while (s === bisher) s = SPRUECHE[Math.floor(Math.random() * SPRUECHE.length)];
  return s as string;
}
